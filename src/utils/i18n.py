# LanguageManager y funciones auxiliares
# ============================================================
class LanguageManager:
    _instance = None
    _current_lang = "es"
    _callbacks = []

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
        return cls._instance

    @classmethod
    def get_language(cls) -> str:
        return cls._current_lang

    @classmethod
    def set_language(cls, lang_code: str) -> None:
        normalized = (lang_code or "es").strip().lower().replace("_", "-")
        normalized = normalized.split("-", 1)[0]
        if normalized not in _TRANSLATIONS:
            normalized = "es"
        cls._current_lang = normalized
        for cb in tuple(cls._callbacks):
            try:
                cb(normalized)
            except Exception:
                # Un callback de una ventana cerrada nunca debe impedir que
                # el resto de la interfaz cambie de idioma.
                continue

    @classmethod
    def register_callback(cls, cb) -> None:
        if cb not in cls._callbacks:
            cls._callbacks.append(cb)

    @classmethod
    def unregister_callback(cls, cb) -> None:
        if cb in cls._callbacks:
            cls._callbacks.remove(cb)

def tr(text: str) -> str:
    lang = LanguageManager.get_language()
    return _TRANSLATIONS.get(lang, {}).get(
        text,
        _TRANSLATIONS["es"].get(text, text),
    )

def set_language(lang_code: str) -> None:
    LanguageManager.set_language(lang_code)

def get_language() -> str:
    return LanguageManager.get_language()
